// Текущий язык
let currentLanguage = localStorage.getItem('language') || 'ru';

// Функция для получения перевода
function t(path) {
  const keys = path.split('.');
  let value = translations[currentLanguage];
  for (let key of keys) {
    value = value?.[key];
  }
  return value || path;
}

// Установка языка
function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLanguage = lang;
  window.currentLanguage = lang;  // Update global reference
  localStorage.setItem('language', lang);
  // Перезагружаем интерфейс с новым языком
  location.reload();
}

// Получение текущего языка
function getLanguage() {
  return currentLanguage;
}

// Глобальная переменная currentLanguage для app.js
window.currentLanguage = currentLanguage;
window.translations = translations;

// Функция для применения переводов ко всем элементам с data-i18n (LEGACY - используется app.js версия)
function applyTranslationsLegacy() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = t(key);
  });
}
