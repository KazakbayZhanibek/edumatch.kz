function tr(key, lang = 'ru') {
  if (lang === 'ru') return null; // Russian is the default, handled inline
  return translations[lang]?.[key] || null;
}

function getLang(req) {
  return req?.query?.lang || req?.headers?.['accept-language']?.split(',')[0]?.split('-')[0] || 'ru';
}

